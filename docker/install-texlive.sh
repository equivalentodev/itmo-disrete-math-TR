#!/bin/sh
set -eu
# Dated, immutable repository; never follow a rolling tlnet/latest mirror.
repository=https://texlive.info/tlnet-archive/2026/08/05/tlnet
installer_sha=7f9e3699b055970e7b272efe740e79eb8e0042748a0c41d7f6b9edc36eb1d24721fd0d5b54b714a8e15af6374811668e3b02f17dfda0fb4e9d98a2691178f68e
case "$(uname -m)" in
  aarch64) platform=aarch64-linux ;;
  x86_64) platform=x86_64-linux ;;
  *) echo 'Supported Docker platforms: linux/amd64 and linux/arm64' >&2; exit 1 ;;
esac
mkdir -p /tmp/install-texlive
cd /tmp/install-texlive
curl --fail --location --retry 3 "$repository/install-tl-unx.tar.gz" -o installer.tar.gz
printf '%s  installer.tar.gz\n' "$installer_sha" | sha512sum --check -
tar -xzf installer.tar.gz --strip-components=1
cat > profile <<EOF
selected_scheme scheme-infraonly
TEXDIR /opt/texlive
TEXMFLOCAL /opt/texlive/texmf-local
TEXMFSYSCONFIG /opt/texlive/texmf-config
TEXMFSYSVAR /opt/texlive/texmf-var
TEXMFCONFIG ~/.texlive2026/texmf-config
TEXMFVAR ~/.texlive2026/texmf-var
binary_$platform 1
instopt_adjustpath 0
instopt_letter 0
instopt_portable 1
tlpdbopt_install_docfiles 0
tlpdbopt_install_srcfiles 0
EOF
perl ./install-tl --repository "$repository" --profile profile
export PATH="/opt/texlive/bin/$platform:$PATH"
# latex-bin also installs Lua engines. Register only the pdfLaTeX format below,
# with the same LaTeX sources; unused XeTeX/LuaTeX engines are not installed.
tlmgr install pdftex metafont mfware latex latexconfig latex-fonts l3kernel l3backend firstaid tools unicode-data \
  latexmk exam amsmath amsfonts graphics pgf babel babel-english \
  babel-russian hyphen-russian cyrillic lh cm-super geometry enumitem setspace
mkdir -p /opt/texlive/texmf-local/web2c
printf '%s\n' 'pdflatex pdftex language.dat -translate-file=cp227.tcx *pdflatex.ini' > /opt/texlive/texmf-local/web2c/fmtutil.cnf
ln -s pdftex "/opt/texlive/bin/$platform/pdflatex"
mktexlsr
fmtutil-sys --byfmt pdflatex
# LH supplies font sources; cm-super supplies outlines, not these TFM metrics.
# Build the common Cyrillic faces now. Other sizes can be generated by Metafont
# into the writable preview font cache at runtime (never into /opt/texlive).
for font in larm1000 labx1000 lati1000 lacc1000; do
  mktextfm "$font"
done
ln -s "$platform" /opt/texlive/bin/current
{
  printf 'repository=%s\ncompiler=pdflatex\ndraft=false\n' "$repository"
  pdflatex --version
  latexmk --version
  awk '/^(name|revision|catalogue-version) /' /opt/texlive/tlpkg/texlive.tlpdb
} > /opt/texlive/manifest.txt
rm -rf /tmp/install-texlive /opt/texlive/tlpkg/backups /root/.texlive2026
